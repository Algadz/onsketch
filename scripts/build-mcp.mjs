// Copies the app modules the MCP Edge Function uses into
// supabase/functions/mcp/_app/ (Supabase only deploys a function's own
// folder). Follows the static imports from the entry files, so only what
// is needed is copied, at the same paths relative to app/src/.
//
//   node scripts/build-mcp.mjs        (run by npm test and before deploying)
//
// _app/ is generated and git-ignored: edit app/src/.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const SRC = new URL('../app/src/', import.meta.url).pathname;
const OUT = new URL('../supabase/functions/mcp/_app/', import.meta.url).pathname;
const ENTRIES = ['core/spec.js', 'core/model.js', 'cloud/cloud.js'];

const IMPORT_RE = /(?:^|[\s;])(?:import|export)\s[^'"]*?from\s*['"](\.{1,2}\/[^'"]+)['"]|(?:^|[\s;])import\s*['"](\.{1,2}\/[^'"]+)['"]/g;

export function moduleGraph(entries = ENTRIES) {
  const seen = new Set();
  const visit = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(IMPORT_RE)) visit(resolve(dirname(file), m[1] || m[2]));
  };
  for (const e of entries) visit(join(SRC, e));
  return [...seen].sort();
}

if (process.argv[1] && process.argv[1].endsWith('build-mcp.mjs')) {
  rmSync(OUT, { recursive: true, force: true });
  const files = moduleGraph();
  for (const f of files) {
    const rel = relative(SRC, f);
    if (rel.startsWith('..')) throw new Error(`${f} is outside app/src`);
    mkdirSync(dirname(join(OUT, rel)), { recursive: true });
    writeFileSync(join(OUT, rel), `// Generated by scripts/build-mcp.mjs from app/src/${rel}: edit that file.\n` + readFileSync(f, 'utf8'));
  }
  console.log(`build-mcp: ${files.length} modules → supabase/functions/mcp/_app/`);
}
