/** The page as written, without the stamp block (npm run stamp adds it). */
export const unstamped = (html) => html.replace(/\n?<!-- stamp:begin[\s\S]*?<!-- stamp:end -->\n?/, '\n');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const html = buildFaq();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = await readFile(OUT, 'utf8'); } catch { /* missing */ }
    if (unstamped(cur).replace(/\s+/g, ' ') !== unstamped(html).replace(/\s+/g, ' ')) { console.error('faq/index.html is out of date: run npm run faq'); process.exit(1); }
  } else {
    // keep the stamp block of the page already there
    let cur = '';
    try { cur = await readFile(OUT, 'utf8'); } catch { /* new */ }
    const stamp = cur.match(/<!-- stamp:begin[\s\S]*?<!-- stamp:end -->/);
    await writeFile(OUT, stamp ? html.replace('</head>', stamp[0] + '\n</head>') : html);
    console.log('wrote faq/index.html');
  }
}
