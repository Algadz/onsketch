const TITLE = 'OnSketch FAQ: drawing tools, dimensions, export and Pro';
const DESCRIPTION = 'How OnSketch works: every drawing tool and shortcut, dimensions and formulas, mechanisms, printing to scale, PNG, SVG and DXF export, and Pro.';

const esc = (t) => String(t).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
/** Answer HTML for the JSON-LD: only the tags Google reads in answers. */
const ldAnswer = (html) => html.replace(/<\/?(kbd|code)>/g, '').replace(/\s+/g, ' ').trim();
const toolById = new Map(TOOLS.map(t => [t.id, t]));

function toolTable(ids) {
  const rows = ids.map(id => {
    const t = toolById.get(id);
    return `<tr><td class="ti">${TOOL_ICONS[id] || ''}</td><th scope="row">${esc(t.label)}</th><td><kbd>${esc(t.key)}</kbd></td><td>${esc(TOOL_LINES[id] || '')}</td></tr>`;
  }).join('\n          ');
  return `<table class="tools">
          <thead><tr><td></td><th scope="col">Tool</th><th scope="col">Key</th><th scope="col">What it does</th></tr></thead>
          <tbody>
          ${rows}
          </tbody>
        </table>`;
}

