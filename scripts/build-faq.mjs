//   node scripts/build-faq.mjs          write the page
//   node scripts/build-faq.mjs --check  exit 1 when the page is out of date
// The questions and answers appear in the page and in its FAQPage
// structured data (JSON-LD) from the same text. Tool icons, names and
// shortcuts come from the editor (app/src/ui/tool-defs.js). Run
// `npm run stamp` afterwards (the page loads one module, theme.js).
