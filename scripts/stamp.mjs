// Cache-busting for the no-build editor.
//
// GitHub Pages lets browsers cache files for ~10 minutes. After a deploy a
// browser can mix a fresh index.html with stale cached modules, and the
// editor fails to start. This writes an import map into app/index.html that
// points every module at `file.js?v=<content hash>`, and stamps the entry
// script and stylesheet the same way, so changed files always load fresh.
//
//   node scripts/stamp.mjs          rewrite app/index.html
//   node scripts/stamp.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const APP = new URL('../app/', import.meta.url).pathname;
const hash = (file) => createHash('sha1').update(readFileSync(file)).digest('hex').slice(0, 10);

function walk(dir) {
  return readdirSync(dir).flatMap(n => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : (p.endsWith('.js') ? [p] : []);
  });
}

export function stampedHtml(html) {
  const files = walk(join(APP, 'src')).sort();
  const imports = {};
  for (const f of files) {
    const rel = './' + relative(APP, f).split('\\').join('/');
    imports[rel] = `${rel}?v=${hash(f)}`;
  }
  const map = `<script type="importmap">\n${JSON.stringify({ imports }, null, 2)}\n</script>`;
  const block = `<!-- stamp:begin (generated by scripts/stamp.mjs) -->\n${map}\n<!-- stamp:end -->`;
  let out = /<!-- stamp:begin[\s\S]*?<!-- stamp:end -->/.test(html)
    ? html.replace(/<!-- stamp:begin[\s\S]*?<!-- stamp:end -->/, block)
    : html.replace('</head>', `${block}\n</head>`);
  out = out.replace(/href="styles\.css(\?v=[0-9a-f]+)?"/, `href="styles.css?v=${hash(join(APP, 'styles.css'))}"`);
  out = out.replace(/src="src\/main\.js(\?v=[0-9a-f]+)?"/, `src="src/main.js?v=${hash(join(APP, 'src/main.js'))}"`);
  return out;
}

const indexPath = join(APP, 'index.html');
if (process.argv[1] && process.argv[1].endsWith('stamp.mjs')) {
  const html = readFileSync(indexPath, 'utf8');
  const next = stampedHtml(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('app/index.html is not stamped; run: npm run stamp'); process.exit(1); }
  } else if (next !== html) {
    writeFileSync(indexPath, next);
    console.log('stamped app/index.html');
  }
}
